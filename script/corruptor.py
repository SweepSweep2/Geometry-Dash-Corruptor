def parse_bmfont_text(file_data):
    font_data = {"info": {}, "common": {}, "page": {}, "chars": [], "kernings": []}
    for line in file_data:
        parts = line.strip().split()
        if not parts:
            continue
        tag = parts[0]
        attrs = {}
        for item in parts[1:]:
            if "=" in item:
                key, val = item.split("=", 1)
                val = val.strip('"')
                if val.lstrip("-").isdigit():
                    val = int(val)
                attrs[key] = val
        if tag in ["info", "common", "page"]:
            font_data[tag] = attrs
        elif tag == "char":
            font_data["chars"].append(attrs)
        elif tag == "kerning":
            font_data["kernings"].append(attrs)
    return font_data

