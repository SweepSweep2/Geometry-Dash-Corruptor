def serialize_bmfont_text(font_data):
    lines = []

    def format_attrs(attrs):
        parts = []
        for key, val in attrs.items():
            if isinstance(val, str) and (" " in val or not val.lstrip("-").lstrip("0123456789").isdigit()):
                parts.append(f'{key}="{val}"')
            else:
                parts.append(f"{key}={val}")
        return " ".join(parts)

    if font_data.get("info"):
        lines.append(f"info {format_attrs(font_data['info'])}")
    if font_data.get("common"):
        lines.append(f"common {format_attrs(font_data['common'])}")
    if font_data.get("page"):
        lines.append(f"page {format_attrs(font_data['page'])}")
    if font_data.get("chars"):
        lines.append(f"chars count={len(font_data['chars'])}")
        for char in font_data["chars"]:
            lines.append(f"char {format_attrs(char)}")
    if font_data.get("kernings"):
        lines.append(f"kernings count={len(font_data['kernings'])}")
        for kerning in font_data["kernings"]:
            lines.append(f"kerning {format_attrs(kerning)}")
    return "\n".join(lines)

