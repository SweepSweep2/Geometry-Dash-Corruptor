def get_all_paths(d, current_path=None):
    if current_path is None:
        current_path = []

    paths = []

    for key, value in d.items():
        path = current_path + [key]

        if isinstance(value, dict):
            paths.extend(get_all_paths(value, path))
        else:
            paths.append(path)

    return paths


